#!/usr/bin/env python3
"""One-shot: build src/data/legal-fallback.ts from the old marketing site's
privacy / terms / sales-terms pages (JSX -> plain HTML).

  python3 scripts/migrate-legal.py /path/to/linkedin-leader/apps/web/app

The source repo is read-only. Deliberate changes to the source text are listed
in docs/CONTENT-SOURCES.md (street address removed, one CIN corrected, links
repointed to this site's slugs)."""
import json, re, sys, pathlib

src = pathlib.Path(sys.argv[1])
out = pathlib.Path(__file__).resolve().parent.parent / 'src/data/legal-fallback.ts'
CIN = 'U72900DL2022PTC395508'  # checked against the public MCA record (entity registry, 2026-10-07)

PAGES = [
    ('privacy-policy', 'privacy/page.tsx', 'Privacy Policy'),
    ('terms-and-conditions', 'terms/page.tsx', 'Terms of Service'),
    ('sales-terms', 'sales-terms/page.tsx', 'Sales Referral Programme Terms'),
]

def convert(jsx: str):
    main = jsx[jsx.index('<main'):jsx.index('</main>')]
    updated = re.search(r'<p className="text-sm text-gray-500[^"]*">(.*?)</p>', main, re.S)
    updated = re.sub(r'\s+', ' ', updated.group(1)).strip() if updated else ''
    body = main[main.index('<section'):main.rindex('</section>') + len('</section>')]
    body = re.sub(r'\{/\*.*?\*/\}', '', body, flags=re.S)
    body = body.replace("{' '}", ' ')
    body = re.sub(r'\s+className="[^"]*"', '', body)
    body = re.sub(r'<Link\b', '<a', body).replace('</Link>', '</a>')
    body = re.sub(r'</?section>', '', body)
    body = body.replace('{new Date().getFullYear()}', '')
    # Repoint links to this site's slugs / the right host.
    body = body.replace('href="/privacy"', 'href="/privacy-policy"').replace('href="/terms"', 'href="/terms-and-conditions"')
    body = re.sub(r'>\s*tyashin\.com\s*</a>', '>linkedin.tyashin.com</a>', body)
    # Company name only — no street address on this site.
    body = body.replace(', registered office: Roop Nagar, Delhi 110007, India)', ')')
    body = re.sub(r'\(CIN\s+' + CIN + r'\),\s*Roop Nagar, Delhi 110007,\s*India\.', '(CIN ' + CIN + '), India.', body)
    body = re.sub(r'CIN:\s*U62099KA2025PTC194291', 'CIN: ' + CIN, body)
    body = re.sub(r'[ \t]*\n\s*', '\n', body)
    body = re.sub(r'\s+</(p|li|h2|h3|a|strong)>', r'</\1>', body)
    body = re.sub(r'<(p|li|h2|h3)>\s+', r'<\1>', body)
    body = re.sub(r'\n+', ' ', body)
    body = re.sub(r'>\s+<(p|ul|ol|li|h2|h3|div)', r'>\n<\1', body).strip()
    if '{' in re.sub(r'&\w+;', '', body):
        raise SystemExit('unconverted JSX expression left in output: ' + body[body.index('{') - 60: body.index('{') + 60])
    return updated, body

rows = []
for slug, rel, title in PAGES:
    updated, html = convert((src / rel).read_text())
    for bad in ('Roop Nagar', 'U62099'):
        assert bad not in html, (slug, bad)
    rows.append(f"  {json.dumps(slug)}: {{\n    title: {json.dumps(title)},\n    updated: {json.dumps(updated, ensure_ascii=False)},\n    html: {json.dumps(html, ensure_ascii=False)},\n  }},")

out.write_text(
    "/**\n * GENERATED by scripts/migrate-legal.py from the previous marketing site's legal\n"
    " * pages. Local fallback only: the live text is whatever the platform legal API\n"
    " * returns for the slug (src/lib/legal.ts). Edit legal text in the platform\n"
    " * admin, not here.\n */\n"
    "export interface LegalFallback {\n  title: string;\n  updated: string;\n  html: string;\n}\n\n"
    "export const legalFallback: Record<string, LegalFallback> = {\n" + "\n".join(rows) + "\n};\n"
)
print('wrote', out, [len(r) for r in rows])
